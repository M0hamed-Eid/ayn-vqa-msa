"""Append-only experiment log.

`reports/` is regenerated (and gitignored) on every run, so it's the wrong
place to remember "what did we already try and how did it score" across
sessions. `experiments.md` lives at the project root, is checked into git,
and only ever grows -- one Markdown table row per scored run -- so dev
score history survives even after `reports/` is wiped and regenerated.

Scoped to Task 1a's fixed 3-metric shape (accuracy / balanced_accuracy /
macro_f1) for now; if a later milestone scores a different task with a
different metric set, this will need a per-task header instead of one
shared table.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from ayn_vqa.evaluate import Metric

_HEADER_METRIC_NAMES = ("accuracy", "balanced_accuracy", "macro_f1")


def _header(metric_names: tuple[str, ...]) -> str:
    columns = ["when (UTC)", "selector", "split", "language", *metric_names]
    return (
        "# Experiment log\n\n"
        "Append-only: one row per scored run. Generated by "
        "`ayn_vqa.experiments.log_experiment`; do not hand-edit past rows.\n\n"
        f"| {' | '.join(columns)} |\n"
        f"|{'---|' * len(columns)}\n"
    )


def log_experiment(
    experiments_md: Path, selector_name: str, split: str, language: str, metrics: list[Metric]
) -> Path:
    if not experiments_md.exists():
        experiments_md.parent.mkdir(parents=True, exist_ok=True)
        experiments_md.write_text(_header(_HEADER_METRIC_NAMES), encoding="utf-8")

    by_name = {m.name: m.value for m in metrics}
    values = " | ".join(f"{by_name.get(name, float('nan')):.4f}" for name in _HEADER_METRIC_NAMES)
    when = datetime.now(UTC).isoformat(timespec="seconds")
    row = f"| {when} | {selector_name} | {split} | {language} | {values} |\n"

    with experiments_md.open("a", encoding="utf-8") as f:
        f.write(row)
    return experiments_md
